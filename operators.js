let x = 2;
let y = 6;
let result = 0;

// Arithmetic Operators
// Addition: +
result = x + y;
console.log(result);

//Subtraction: -
result = y - x;
console.log(result);

// Multiplication: *
result = x * y;
console.log(result);

// Division: /
result = y / x;
console.log(result);

// Modulus(Reminder): %
result = y % x;
console.log(result);

// Short-hand Operators
x += y;
console.log(x);

y -= x;
console.log(y);

x *= y;
console.log(x);

y /= x;
console.log(y);

// Increment & Decrement
let num1 = 2;
let num2 = 3;

// increment: ++
num1++;
console.log(num1);

num2++;
console.log(num2);

